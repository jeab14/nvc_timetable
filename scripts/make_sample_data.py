        ("20000-2001", "กิจกรรมลูกเสือวิสามัญ 1", "0-2-0", "GEN", ""),
        ("20204-2001", "คอมพิวเตอร์และสารสนเทศเพื่องานอาชีพ", "1-2-2", "DBT", "ห้องคอมพิวเตอร์"),
        ("21910-1001", "ธุรกิจดิจิทัลเบื้องต้น", "2-0-2", "DBT", ""),
        ("21910-2003", "ระบบเครือข่ายคอมพิวเตอร์", "1-3-2", "DBT", "ห้องคอมพิวเตอร์"),
        ("21910-2004", "อินเทอร์เน็ตในงานธุรกิจดิจิทัล", "1-2-2", "DBT", "ห้องคอมพิวเตอร์"),
        ("20201-2001", "การบัญชีเบื้องต้น 1", "2-2-3", "ACC", "ห้องคอมพิวเตอร์"),
